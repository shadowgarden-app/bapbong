import { formatNumber } from './number-format.js';

describe('formatNumber (Excel format codes)', () => {
  it.each([
    [0.862, '0.0%', '86.2%'],
    [0.449, '0.0%', '44.9%'],
    [0, '0.0%', '0.0%'],
    [0.5, '0%', '50%'],
    [1, '0%', '100%'],
    [1521.39, 'General', '1521.39'],
    [1600, 'General', '1600'],
    [0.86199999999999999, 'General', '0.862'],
    [1234567.891, '#,##0.00', '1,234,567.89'],
    [1234567, '#,##0', '1,234,567'],
    [-1234, '#,##0', '-1,234'],
    [-1234, '#,##0;(#,##0)', '(1,234)'],
    [0, '#,##0;(#,##0);"-"', '-'],
    [12.5, '$#,##0.00', '$12.50'],
    [12.5, '[$€-407]#,##0.00', '€12.50'],
    [1500000, '#,##0,,"M"', '2M'],
    [0.000012, 'General', '1.2E-05'],
    [123456789012, 'General', '1.23457E+11'],
    [12345, '0.00E+00', '1.23E+04'],
    [3.14159, '0.##', '3.14'],
    [3, '0.##', '3.'],
    [41275, 'm/d/yyyy', '1/1/2013'],
    [41275, 'mmm-yy', 'Jan-13'],
    [41275.5, 'h:mm AM/PM', '12:00 PM'],
    [7, '0 "units"', '7 units'],
  ])('%s with %s → %s', (v, code, out) => {
    expect(formatNumber(v as number, code as string)).toBe(out);
  });
});
