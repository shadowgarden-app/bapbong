/**
 * Decode one EXTTEXTOUT string given the facename of the font it was drawn
 * with. Bytes without a table entry become U+FFFD.
 */
export function decodeWmfText(bytes: Uint8Array, face: string): string {
  const table =
    face === 'Symbol' ? SYMBOL : face === 'MT Extra' ? MT_EXTRA : null;
  let out = '';
  for (const b of bytes) {
    if (table) out += String.fromCharCode(table[b] ?? 0xfffd);
    else if (b >= 0x80 && b <= 0x9f)
      out += String.fromCharCode(CP1252_80_9F[b - 0x80]);
    else out += String.fromCharCode(b);
  }
  return out;
}
