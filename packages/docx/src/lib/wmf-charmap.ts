/**
 * Byte → Unicode for the non-Unicode fonts MathType WMF previews draw with.
 *
 * EXTTEXTOUT strings are single-byte codes in the SELECTED FONT's own
 * encoding. `Times New Roman` runs are windows-1252; `Symbol` and `MT Extra`
 * are symbol fonts whose bytes index glyphs, not characters — the facename,
 * not the LogFont charset, decides (MathType writes charset 0/DEFAULT even
 * for Symbol).
 *
 * Symbol: the classic Adobe/Windows Symbol layout (per Mozilla's MathML font
 * encoding tables). Where Adobe used private-use codes for glyph PIECES —
 * the top/extender/bottom fragments tall delimiters are assembled from —
 * modern Unicode has real codepoints (U+239B…U+23AD etc.), and those are
 * mapped so any math-capable fallback font can draw them.
 *
 * MT Extra: Mozilla's documented table, plus 0xA1 → ℝ and 0xA2 → ℤ which
 * postdate it — verified against the MTEF stream MathType embeds beside the
 * drawing records (MTCode 0x211D/0x2124 in the same files).
 *
 * Unmapped bytes decode to U+FFFD: visibly wrong beats silently wrong, and
 * the replacement mark in output is the signal a table entry is missing.
 */

